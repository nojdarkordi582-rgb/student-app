if nav:
    st.success(f"سلاڤ، {nav}! سەرکەفتن بۆتە دخوازیین.")

menu = st.selectbox("تکایە خزمەتگوزارییەکێ هەلبژێرە:", [
    "شیکارکرنا هەمی بابەتان (بە پشک و ژمارەیی) 📖",
    "دیتنا خشتەیا رۆژی (وانە) 📅",
    "ئامۆژگاریێن خوەیندنێ و خۆشیێ 💡",
    "نڤیسین و پاشەکەوتکرنا تێبینیەکێ 📝"
])

if menu == "شیکارکرنا هەمی بابەتان (بە پشک و ژمارەیی) 📖":
    st.subheader("--- شیکارکەرێ پرسیارێن پەڕتووکی (هەمی بابەت) ---")
    
    subject_category = st.selectbox("تکایە بابەتی هەلبژێرە:", [
        "بیرکاری (Mathematics)",
        "فیزیا و کیمیا (Physics & Chemistry)",
        "مێژوو و جۆگرافیا (History & Geography)",
        "زمان و وێژە (Literature & Languages)",
        "زینده‌وه‌رزانی (Biology)"
    ])

    uploaded_file = st.file_uploader("وێنەیەکێ پرسیارێ باربکە (ئەگەر هەبێت):", type=["jpg", "jpeg", "png"])

    if uploaded_file is not None:
        image = Image.open(uploaded_file)
        st.image(image, caption="وێنەیێ پرسیارێ یێ هاتییە بارکرن", use_container_width=True)

    question_text = st.text_input("یان دەقێ پرسیارێ (نڤیسین) لێرە بنڤیسە:")

    if st.button("دەرئێخستنا شیکاریا تەواو"):
        with st.spinner("خەریکی ڕێکخستن و حلکرنا پرسیارێ مە..."):
            st.success("✅ شیکاریا پرسیارێ ب سەرکەفتن هاتە ئەنجامدان!")
            
            if "بیرکاری" in subject_category:
                st.info("📌 **شیکاریا پشک بە پشک بۆ بیرکاری:**")
                st.write("1. **شیکردنەوەی بنەڕەتی:** دۆزینەوەی فاکتەرە هاوبەشەکان و مەخرەجی کسرەکان.")
                st.write("2. **ئەنجامدانی ئۆپەراسیۆنەکان:** یەکخستنی هاوکێشەکان بە شێوازێکی زانستی.")
                st.write("3. **ڕێکخستنی تێرمەکان:** گواستنەوەی ژمارە و گۆڕاوەکان بۆ هەردوو لای هاوکێشەکە.")
                st.error("🎯 **ئەنجامێ کۆتایی:** بەدەستهێنانی بەهای ڕاستەقینەی گۆڕاوەکە ($x$).")
            
            elif "فیزیا" in subject_category:
                st.info("📌 **شیکاریا پشک بە پشک بۆ فیزیا و کیمیا:**")
                st.write("1. **دیارکردنا داتایان:** نووسینی بڕە دراوەکان ($v, m, F, t$).")
                st.write("2. **هەڵبژاردنی یاسا:** نووسینی یاسای گونجاو بۆ پرسیارەکە.")
                st.write("3. **جێگیرکردنی ژمارەکان:** دانانی بەهاکان لە شوێنی خۆیان.")
                st.error("🎯 **ئەنجامێ کۆتایی:** ئەنجامی ژمارەیی لەگەڵ یەکەی پێوانەکردنی دروست.")

            elif "مێژوو" in subject_category:
                st.info("📌 **شیکاریا پشک بە پشک بۆ مێژوو و جۆگرافیا:**")
                st.write("1. **کات و شوێن:** دەستنیشانکرنی مێژووی ڕووداوەکە و ناوچەی جوگرافی.")
                st.write("2. **هۆکارەکان:** شیکارکردنی هۆکارێن سەرەکیی سەرهەڵدانی ڕووداوەکە.")
                st.write("3. **کاریگەری و دەرئەنجام:** گرنگیی ڕووداوەکە لە سەردەمی خۆیدا.")
                st.error("🎯 **پوختەی کۆتایی:** وەڵامدانەوەیەکی مێژوویی ورد و پوخت.")

            elif "زمان" in subject_category:
                st.info("📌 **شیکاریا پشک بە پشک بۆ زمان و وێژە:**")
                st.write("1. **ڕستەسازی و ڕێزمان:** دیارکردنی بنەما زمانەڤانییەکان.")
                st.write("2. **لایەنی ئەدەبی:** ناساندنی ئاماژە و جوانکارییەکانی دەقەکە.")
                st.error("🎯 **پوختەی کۆتایی:** ڕوونکردنەوەیەکی تێر و تەسەل.")

            else:
                st.info("📌 **شیکاریا پشک بە پشک بۆ زیندەوەرورزانی:**")
                st.write("1. **خانە و ئەندامەکان:** ناساندنی پێکهاتەی بایۆلۆجی.")
                st.write("2. **کردارە حیۆتییەکان:** ڕوونکردنەوەی گۆڕانکارییە زانستییەکان.")
                st.error("🎯 **ئەنجامێ کۆتایی:** پوختەی زانستیی پرسیارەکە.")

elif menu == "دیتنا خشتەیا رۆژی (وانە) 📅":
    st.subheader("--- خشتەیا وانەیێن هەفتەیی ---")
    st.write("• **شەممە:** بیرکاری و زانست")
    st.write("• **دووشەممە:** فیزیا و کیمیا")
    st.write("• **سێشەممە:** مێژوو و وێژە")

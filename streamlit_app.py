import streamlit as st
from PIL import Image

st.title("📚 بەرنامەیێ قوتابیان و پەرەپێدانا خوەندنێ")

nav = st.text_input("تکایە ناڤێ خۆ بنڤیسە:")

if nav:
    st.success(f"سلاڤ، {nav}! ئەم سەرکەفتنێ بۆتە دخوازیین.")

menu = st.selectbox("تکایە خزمەتگوزارییەکێ هەلبژێرە:", [
    "دیتنا خشتەیا رۆژی (وانە)",
    "ئامۆژگاریێن خوەیندنێ و خۆشیێ 💡",
    "نڤیسین و پاشەکەوتکرنا تێبینیەکێ 📝",
    "شەرحکرنا بابەتێن زانستی و ئەدەبی 🤖"
])

if menu == "دیتنا خشتەیا رۆژی (وانە)":
    st.subheader("--- خشتەیا وانەیێن هەفتەیی ---")
    st.write("• **شەممە:** پایتۆن و فێربوونا بەرنامەسازیی")
    st.write("• **دووشەممە:** ریاضیات و زانست")
    st.write("• **سێشەممە:** ئینگلیزی و مێژوو")
    st.write("• **چارشەممە:** وەرزش و چالاکی")
    st.write("• **پێنجشەممە:** تاقیکردنەوە و پشوو")

elif menu == "ئامۆژگاریێن خوەیندنێ و خۆشیێ 💡":
    st.subheader("--- ئامۆژگاریێن خوەیندنێ و خۆشیێ 💡 ---")
    st.markdown("1. هەمیشە دەمێ خۆ ڕێکخە و پۆمۆدۆرۆ تاقی بکە.")
    st.markdown("2. شوێنێ خوێندنێ گوهڕە یان قەلەمێن ڕەنگاوڕەنگ بەکاربینە.")
    st.markdown("3. باوەریا تە ب خۆ هەبێت، تو دشکەی سەرکەفتنی بدەستی!")

elif menu == "نڤیسین و پاشەکەوتکرنا تێبینیەکێ 📝":
    st.subheader("--- پشکا تێبینیان 📝 ---")
    note = st.text_area("تێبینیا خۆ ل ڤێرە بنڤیسە:")
    if st.button("پاشەکەوتکرنا تێبینیێ"):
        if note:
            st.success(f'✅ پەیاما تە ب سەرکەفتن هاتە وەرگرتن: "{note}"')
        else:
            st.warning("⚠️ تکایە نیشانەیەک یان تێبینیەک بنڤیسە پێش ئەوەی دگرتی.")

elif menu == "شەرحکرنا بابەتێن زانستی و ئەدەبی 🤖":
    st.subheader("--- هاریکارێ شیکاریا زانستی و ئەدەبی 🤖 ---")
    
    subject_type = st.selectbox("جۆرێ بابەتی هەلبژێرە:", [
        "بیرکاری (Math)",
        "زانست و فیزیا (Science & Physics)",
        "مێژوو و کۆمەڵایەتی (History & Social)",
        "زمان و وێژە (Literature & Languages)"
    ])

    uploaded_file = st.file_uploader("وێنەیەکێ پرسیارێ باربکە (ئەگەر هەبێت):", type=["jpg", "jpeg", "png"])

    if uploaded_file is not None:
        image = Image.open(uploaded_file)
        st.image(image, caption="وێنەیێ هاتییە بارکرن", use_container_width=True)

    user_query = st.text_input("یان ناڤێ بابەتی / پرسیارێ لێرە بنڤیسە:")

    if st.button("دەرئێخستنا زانیاری و نهێنیان"):
        with st.spinner("خەریکی شیکارکردن و دەرئێخستنا نهێنیێن بابەتی مە..."):
            st.success("✅ شیکارکردن تەواو بوو!")
            
            if "بیرکاری" in subject_type:
                st.info("💡 **شیکاریا نهێنی و ڕێگەی حلکردنا بیرکاری:**")
                st.write("1. **دیارکردنا داتایان:** سەرەتا نەخشە و ژمارەیێن سەرەکی ل پرسیارێ جودا بکە.")
                st.write("2. **یاسایێن په‌یوەندیدار:** یاسایێن گونجاو بکاربینە (بۆ نموونە: هاوکێشەیێن گۆڕاو یان ئەندازەیی).")
                st.write("3. **ئەنجام:** پشک بە پشک حل بکە تا دگەیشتییە ئەنجامێ ڕاست.")
            
            elif "زانست" in subject_type:
                st.info("💡 **نهێنی و زانیاریێن زانستی (Science Insights):**")
                st.write("1. **تێگەهشتن:** ئەم بابەتە پشت بەستن ب یاسایێن سروشتی و تاقیگەیی دکەت.")
                st.write("2. **خاڵێن سەرەکی:** هەمیشە هۆکار و دەرئەنجام لە بەرچاو بگرە.")
                st.write("3. **ئامۆژگاری:** بەکارهێنانی وێنە و خشتە بۆ لەبیرنەکردنا زانیارییان.")

            elif "مێژوو" in subject_type:
                st.info("💡 **پوختە و نهێنیێن مێژوویی:**")
                st.write("1. **ساڵ و ڕووداو:** گرنگترین بەش ئەوەیە ساڵ، کەسایەتی و شوێن بەیەکەوە گرێ بدەیت.")
                st.write("2. **کاریگەری:** تێگەهشتن ژ وێ چەندێ کە چۆن ئەو ڕووداوە پەرەسەند.")

            else:
                st.info("💡 **شیکاریا وێژەیی و زمان:**")
                st.write("1. **واتایێن قووڵ:** سەرنج لە مەبەستی سەرەکی نووسەر یان هۆنراوە بنە.")
                st.write("2. **خاڵێن گرنگ:** دەستنیشانکرنا وشە و ڕستە سەرەکییەکان.")
                

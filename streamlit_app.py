import streamlit as st
from PIL import Image

# دابینکری بۆ ڕێکوپێکرنا نڤیسینێ ژ ڕاست بۆ چەپ (RTL)
st.markdown(
    """
    <style>
    body, .stApp {
        direction: rtl;
        text-align: right;
    }
    </style>
    """,
    unsafe_allow_html=True
)

st.title("📚 بەرنامەیێ قوتابیان و شیکارکەرێ پەڕتووکی")

nav = st.text_input("تکایە ناڤێ خۆ بنڤیسە:")

if nav:
    st.success(f"سلاڤ، {nav}! ئەم سەرکەفتنێ بۆتە دخوازیین.")

menu = st.selectbox("تکایە خزمەتگوزارییەکێ هەلبژێرە:", [
    "شیکارکرنا پرسیاران (پشک بە پشک و ژمارەیی) 📖",
    "دیتنا خشتەیا رۆژی (وانە) 📅",
    "ئامۆژگاریێن خوەیندنێ و خۆشیێ 💡",
    "نڤیسین و پاشەکەوتکرنا تێبینیەکێ 📝"
])

if menu == "شیکارکرنا پرسیاران (پشک بە پشک و ژمارەیی) 📖":
    st.subheader("--- شیکارکەرێ پرسیارێن پەڕتووکی ---")
    
    subject_type = st.selectbox("جۆرێ بابەتی هەلبژێرە:", [
        "هاوکێشەی ڕێژەیی (Rational Equations)",
        "فیزیا (Physics Laws)",
        "مێژوو و زانست (History & Science)"
    ])

    uploaded_file = st.file_uploader("وێنەیەکێ پرسیارێ باربکە (ئەگەر هەبێت):", type=["jpg", "jpeg", "png"])

    if uploaded_file is not None:
        image = Image.open(uploaded_file)
        st.image(image, caption="وێنەیێ پرسیارێ یێ هاتییە بارکرن", use_container_width=True)

    question_text = st.text_input("یان دەقێ پرسیارێ (نڤیسین) لێرە بنڤیسە:")

    if st.button("دەرئێخستنا شیکاریا پەڕتووکی"):
        with st.spinner("خەریکی حلکردن و ڕێکخستنا هەنگاڤا مە..."):
            st.success("✅ شیکاریا پرسیارێ ب سەرکەفتن تەواو بوو!")
            
            if "هاوکێشەی ڕێژەیی" in subject_type:
                st.info("📌 **شیکاریا پشک بە پشک (وەک نموونەیا پەڕتووکێ):**")
                st.write("1. **دیارکردنا مەخرەج:** $4x^2 - 9 = (2x - 3)(2x + 3)$")
                st.write("2. **یەکخستنی کسرەکان:** دۆزینەوەی مەخرەجی هاوبەش بۆ هەموو لایەک.")
                st.write("3. **لێکدان و کورتکردنەوە:** لێکدانی هەردوو لا بە مەخرەجی هاوبەش بۆ لابردنی کسرەکان.")
                st.write("4. **ڕێکخستنی کۆتایی:** گواستنەوەی تێرمەکان بۆ لایەک و سفرکردنی لایەکەی تر: $6x^2 - 3x - 9 = 2x^2 - 3x$")
                st.error("🎯 **ئەنجامێ کۆتایی:** $x = -\\frac{3}{2}$ یان $x = \\frac{3}{2}$")
            
            elif "فیزیا" in subject_type:
                st.info("📌 **شیکاریا زانستی و فیزیکی:**")
                st.write("1. **داتا و زانیاریێن هاتییە دان:** دەستنیشانکرنا بڕە سەرەکییەکان.")
                st.write("2. **یاسایێن گونجاو:** بەکارهێنانی یاسای بنەڕەتی.")
                st.error("🎯 **ئەنجامێ کۆتایی:** بەدەستهێنانی بەهاکە لەگەڵ یەکەی فیزیکی.")

            else:
                st.info("📌 **شیکاریا بابەتی:**")
                st.write("1. **خاڵێن سەرەکی:** شیکارکردنی ناوەڕۆک بە پێی ڕێزبەندی زانستی و وێژەیی.")
                st.error("🎯 **پوختەی کۆتایی:** وەڵامدانەوەیەکی ورد و پشک بە پشک.")

elif menu == "دیتنا خشتەیا رۆژی (وانە) 📅":
    st.subheader("--- خشتەیا وانەیێن هەفتەیی ---")
    st.write("• **شەممە:** پایتۆن و فێربوونا بەرنامەسازیی")
    st.write("• **دووشەممە:** ریاضیات و زانست")
    st.write("• **سێشەممە:** ئینگلیزی و مێژوو")

elif menu == "ئامۆژگاریێن خوەیندنێ و خۆشیێ 💡":
    st.subheader("--- ئامۆژگاریێن خوەیندنێ و خۆشیێ 💡 ---")
    st.markdown("1. هەمیشە دەمێ خۆ ڕێکخە و پۆمۆدۆرۆ تاقی بکە.")
    st.markdown("2. باوەریا تە ب خۆ هەبێت، تو دشکەی سەرکەفتنی بدەستی!")

elif menu == "نڤیسین و پاشەکەوتکرنا تێبینیەکێ 📝":
    st.subheader("--- پشکا تێبینیان 📝 ---")
    note = st.text_input("تێبینیا خۆ ل ڤێرە بنڤیسە:")
    if st.button("پاشەکەوتکرنا تێبینیێ"):
        if note:
            st.success(f'✅ پەیاما تە ب سەرکەفتن هاتە وەرگرتن: "{note}"')
            

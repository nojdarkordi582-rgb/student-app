import streamlit as st
from PIL import Image

# دابینکری بۆ ڕێکوپێکرنا نڤیسینێ ژ ڕاست بۆ چەپ (RTL)
st.markdown(
    """
    <style>
    body, .stApp {
        direction: rtl;
        text-align: right;
    }
    </style>
    """,
    unsafe_allow_html=True
)

st.title("📚 بەرنامەیێ قوتابیان و شیکارکەرێ پرسیاران")

nav = st.text_input("تکایە ناڤێ خۆ بنڤیسە:")

if nav:
    st.success(f"سلاڤ، {nav}! ئەم سەرکەفتنێ بۆتە دخوازیین.")

menu = st.selectbox("تکایە خزمەتگوزارییەکێ هەلبژێرە:", [
    "دیتنا خشتەیا رۆژی (وانە)",
    "ئامۆژگاریێن خوەیندنێ و خۆشیێ 💡",
    "نڤیسین و پاشەکەوتکرنا تێبینیەکێ 📝",
    "شیکارکرنا پرسیارێن زانستی و بیرکاری 🤖"
])

if menu == "دیتنا خشتەیا رۆژی (وانە)":
    st.subheader("--- خشتەیا وانەیێن هەفتەیی ---")
    st.write("• **شەممە:** پایتۆن و فێربوونا بەرنامەسازیی")
    st.write("• **دووشەممە:** ریاضیات و زانست")
    st.write("• **سێشەممە:** ئینگلیزی و مێژوو")
    st.write("• **چارشەممە:** وەرزش و چالاکی")
    st.write("• **پێنجشەممە:** تاقیکردنەوە و پشوو")

elif menu == "ئامۆژگاریێن خوەیندنێ و خۆشیێ 💡":
    st.subheader("--- ئامۆژگاریێن خوەیندنێ و خۆشیێ 💡 ---")
    st.markdown("1. هەمیشە دەمێ خۆ ڕێکخە و پۆمۆدۆرۆ تاقی بکە.")
    st.markdown("2. شوێنێ خوێندنێ گوهڕە یان قەلەمێن ڕەنگاوڕەنگ بەکاربینە.")
    st.markdown("3. باوەریا تە ب خۆ هەبێت، تو دشکەی سەرکەفتنی بدەستی!")

elif menu == "نڤیسین و پاشەکەوتکرنا تێبینیەکێ 📝":
    st.subheader("--- پشکا تێبینیان 📝 ---")
    note = st.text_area("تێبینیا خۆ ل ڤێرە بنڤیسە:")
    if st.button("پاشەکەوتکرنا تێبینیێ"):
        if note:
            st.success(f'✅ پەیاما تە ب سەرکەفتن هاتە وەرگرتن: "{note}"')
        else:
            st.warning("⚠️ تکایە نیشانەیەک یان تێبینیەک بنڤیسە پێش ئەوەی دگرتی.")

elif menu == "شیکارکرنا پرسیارێن زانستی و بیرکاری 🤖":
    st.subheader("--- شیکارکەرێ پرسیارێن پرۆفیشناڵ 🤖 ---")
    
    subject_type = st.selectbox("جۆرێ بابەتی هەلبژێرە:", [
        "بیرکاری (Math - معادلات و حساب)",
        "فیزیا و کیمیا (Physics & Chemistry)",
        "زمان و وێژە (Literature)"
    ])

    uploaded_file = st.file_uploader("وێنەیەکێ پرسیارێ باربکە:", type=["jpg", "jpeg", "png"])

    if uploaded_file is not None:
        image = Image.open(uploaded_file)
        st.image(image, caption="وێنەیێ پرسیارێ یێ هاتییە بارکرن", use_container_width=True)

    question_text = st.text_input("یان دەقێ پرسیارێ (نڤیسین) لێرە بنڤیسە:")

    if st.button("پێشکێشکرنا شیکاریا تەواو"):
        with st.spinner("خەریکی حلکرن و شیکاریا پرسیارێ مە..."):
            st.success("✅ شیکاریا پرسیارێ تەواو بوو!")
            
            if "بیرکاری" in subject_type:
                st.info("📌 **شیکاریا ڕاستەقینە و حلکردنا پرسیارا بیرکاری:**")
                st.write("• **نەخشەی گشتی:** لێرەدا هاوکێشە یان پرسیارە هاتییە پۆلێنکرن.")
                st.write("• **هەنگاڤا ١:** گۆڕاوەکان (Variables) لایەک و ژمارەکان لایەک دانێ.")
                st.write("• **هەنگاڤا ٢:** بەکارهێنانی یاسای گونجاو (بۆ نموونە: هاوکێشەی پلە دوو یان ئەندازەیی).")
                st.error("🎯 **ئەنجامێ کۆتایی:** x = 5 (بۆ نموونەی پرسیارەکە)")
            
            elif "فیزیا" in subject_type:
                st.info("📌 **شیکاریا پرسیارا فیزیا و زانستی:**")
                st.write("• **داتا و زانیاریێن هاتییە دان:** (Given Data) دەستنیشانکرنا لەز، کێش، یان هێز.")
                st.write("• **یاسایە هاتییە بکاربینن:** $F = m \cdot a$ یان یاسایێن تری گونجاو.")
                st.error("🎯 **ئەنجامێ کۆتایی:** بەرهەمێ حلکرنێ ب یەکەیێن فیزیکی (N یان m/s).")

            else:
                st.info("📌 **شیکاریا بابەتی:**")
                st.write("• **خاڵێن سەرەکی:** وەڵاما ڤی بابەتی پشت بە داتایێن نڤیساری و تێگەهشتنا زمانەڤانی دکەت.")
                st.error("🎯 **پوختەیا وەڵامێ:** مانا سەرەکی ئەوە کە هۆکار و دەرئەنجام ب ڕێکوپێکی بێنە دیارکرن.")
                

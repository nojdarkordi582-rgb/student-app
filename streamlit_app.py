st.markdown("---")
st.markdown("<div class='glowing-box' style='font-size: 18px;'>👨‍💻 دروستکەر و گەشەپێدەری بەرنامەی: نوژدار دژوار دۆسکی</div>", unsafe_allow_html=True)

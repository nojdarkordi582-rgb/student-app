import streamlit as st
from PIL import Image

# دابینکری بۆ ڕێکوپێکرنا نڤیسینێ ژ ڕاست بۆ چەپ (RTL) و جوانکارییا سەکۆیێ
st.markdown(
    """
    <style>
    body, .stApp {
        direction: rtl;
        text-align: right;
    }
    </style>
    """,
    unsafe_allow_html=True
)

st.title("📚 بەرنامەیێ قوتابیان و شیکارکەرێ پرسیارێن پرۆفیشناڵ")

nav = st.text_input("تکایە ناڤێ خۆ بنڤیسە:")

if nav:
    st.success(f"سلاڤ، {nav}! سەرکەفتن بۆتە دخوازیین.")

menu = st.selectbox("تکایە خزمەتگوزارییەکێ هەلبژێرە:", [
    "دیتنا خشتەیا رۆژی (وانە)",
    "ئامۆژگاریێن خوەیندنێ و خۆشیێ 💡",
    "نڤیسین و پاشەکەوتکرنا تێبینیەکێ 📝",
    "شیکارکرنا هەمی بابەتێن زانستی و ئەدەبی 🤖"
])

if menu == "دیتنا خشتەیا رۆژی (وانە)":
    st.subheader("--- خشتەیا وانەیێن هەفتەیی ---")
    st.write("• **شەممە:** پایتۆن و فێربوونا بەرنامەسازیی")
    st.write("• **دووشەممە:** ریاضیات و زانست")
    st.write("• **سێشەممە:** ئینگلیزی و مێژوو")
    st.write("• **چارشەممە:** وەرزش و چالاکی")
    st.write("• **پێنجشەممە:** تاقیکردنەوە و پشوو")

elif menu == "ئامۆژگاریێن خوەیندنێ و خۆشیێ 💡":
    st.subheader("--- ئامۆژگاریێن خوەیندنێ و خۆشیێ 💡 ---")
    st.markdown("1. هەمیشە دەمێ خۆ ڕێکخە و پۆمۆدۆرۆ تاقی بکە.")
    st.markdown("2. شوێنێ خوێندنێ گوهڕە یان قەلەمێن ڕەنگاوڕەنگ بەکاربینە.")
    st.markdown("3. باوەریا تە ب خۆ هەبێت، تو دشکەی سەرکەفتنی بدەستی!")

elif menu == "نڤیسین و پاشەکەوتکرنا تێبینیەکێ 📝":
    st.subheader("--- پشکا تێبینیان 📝 ---")
    note = st.text_area("تێبینیا خۆ ل ڤێرە بنڤیسە:")
    if st.button("پاشەکەوتکرنا تێبینیێ"):
        if note:
            st.success(f'✅ پەیاما تە ب سەرکەفتن هاتە وەرگرتن: "{note}"')
        else:
            st.warning("⚠️ تکایە نیشانەیەک یان تێبینیەک بنڤیسە پێش ئەوەی دگرتی.")

elif menu == "شیکارکرنا هەمی بابەتێن زانستی و ئەدەبی 🤖":
    st.subheader("--- شیکارکەرێ پرسیارێن پرۆفیشناڵ (ب هەموو هەنگاوان) ---")
    
    subject_type = st.selectbox("جۆرێ بابەتی هەلبژێرە:", [
        "بیرکاری و هاوکێشە (Mathematics)",
        "فیزیا و کیمیا (Physics & Chemistry)",
        "مێژوو و جۆگرافیا (History & Geography)",
        "زمان و وێژە (Literature & Languages)"
    ])

    uploaded_file = st.file_uploader("وێنەیەکێ پرسیارێ باربکە:", type=["jpg", "jpeg", "png"])

    if uploaded_file is not None:
        image = Image.open(uploaded_file)
        st.image(image, caption="وێنەیێ پرسیارێ یێ هاتییە بارکرن", use_container_width=True)

    question_text = st.text_input("یان دەقێ پرسیارێ (نڤیسین) لێرە بنڤیسە:")

    if st.button("پێشکێشکرنا شیکاریا تەواو و ب هەنگاو"):
        with st.spinner("خەریکی شیکارکردنا پرسیارێ مە بە شێوازێ پەڕتووکی..."):
            st.success("✅ شیکاریا پرسیارێ ب سەرکەفتن هاتە ئەنجامدان!")
            
            if "بیرکاری" in subject_type:
                st.info("📌 **شیکاریا پشک بە پشک و ورد بۆ بیرکاری:**")
                st.write("1. **شیکردنەوەی مەخرەج یان فاکتەرکردن:** $4x^2 - 9 = (2x - 3)(2x + 3)$")
                st.write("2. **دۆزینەوەی بەهای هاوبەش:** یەکخستنی کسرەکان لە ڕێگەی مەخرەجی هاوبەش.")
                st.write("3. **ئەنجامدانی لێکدان و کورتکردنەوە:** پاککردنەوەی هاوکێشەکە لە کسرەکان.")
                st.write("4. **ڕێکخستنی هاوکێشەی کۆتایی:** گواستنەوەی تێرمەکان و سفرکردنی لایەک: $6x^2 - 3x - 9 = 2x^2 - 3x$")
                st.error("🎯 **ئەنجامێ کۆتایی:** $x = -\\frac{3}{2}$ یان $x = \\frac{3}{2}$")
            
            elif "فیزیا" in subject_type:
                st.info("📌 **شیکاریا پشک بە پشک بۆ فیزیا و کیمیا:**")
                st.write("1. **دیارکردنا داتایێن هاتییە دان:** دەستنیشانکرنا بڕە زانستییەکان ($v, m, F, t$).")
                st.write("2. **هەڵبژاردنی یاسای گونجاو:** نووسینی یاسای بنەڕەتی (بۆ نموونە: $F = m \\cdot a$).")
                st.write("3. **جێگیرکردنی ژمارەکان لە یاساکەدا:** دانانی بەهاکان لە شوێنی خۆیان.")
                st.error("🎯 **ئەنجامێ کۆتایی:** بەدەستهێنانی بەهاکە لەگەڵ یەکەی زانستیی ڕاستەقینە.")

            elif "مێژوو" in subject_type:
                st.info("📌 **شیکاریا پوختە و پشک بە پشک بۆ مێژوو و کۆمەڵایەتی:**")
                st.write("1. **دیارکردنا کات و شوێن:** دەستنیشانکرنا ساڵ و شوێنێ ڕووداوێ.")
                st.write("2. **کەسایەتییە سەرەکییەکان:** ناساندنی ڕۆڵی کەسایەتییە کاریگەرەکان.")
                st.write("3. **هۆکار و دەرئەنجام:** شیکارکردنا هۆکارێن سەرهەڵدانێ و کاریگەرییەکانی لەسەر سەردەمی خۆی.")
                st.error("🎯 **پوختەی کۆتایی:** دەرئەنجامی مێژوویی و وەرگرتنی پەند.")

            else:
                st.info("📌 **شیکاریا پشک بە پشک بۆ زمان و وێژە:**")
                st.write("1. **شیکارکردنا ڕستە و دەق:** دیارکردنا وشە سەرەکی و بنچینەییەکان.")
                st.write("2. **لایەنی ڕێزمان و جوانی:** دەستنیشانکرنا یاسایێن زمانەڤانی یان ئاماژە و وێنەیێن ئەدەبی.")
                st.write("3. **مەبەستی سەرەکی نووسەر:** تێگەهشتنا قووڵا مانایێ.")
                st.error("🎯 **پوختەی کۆتایی:** وەڵامدانەوەیەکی ورد و ئەدەبی.")
                
